/**
 * Central Proctoring Media Guard
 * Adapted from ViBe (vicharanashala/vibe) proctoring architecture.
 *
 * Provides:
 * 1. Virtual Camera Detection (prevents spoofing via OBS, Snap Camera, DroidCam, etc.)
 * 2. Camera Stream Quality Sanity Checks (flags impossible resolutions / FPS)
 * 3. Unified media stream verification
 */

export interface VirtualCameraCheck {
  isVirtual: boolean;
  confidence: "low" | "medium" | "high";
  reason: string;
  matchedLabel?: string;
  matchedDeviceId?: string;
}

export interface StreamQualityCheck {
  isSuspicious: boolean;
  reason: string;
}

export type ProctoringViolation =
  | ({ type: "VIRTUAL_CAMERA"; severity: "HIGH" } & VirtualCameraCheck)
  | ({ type: "CAMERA_QUALITY"; severity: "MEDIUM" } & StreamQualityCheck);

export const SUSPICIOUS_CAMERA_KEYWORDS = [
  "obs",
  "virtual",
  "snap",
  "manycam",
  "droidcam",
  "epoccam",
  "camlink",
  "vcam",
  "xsplit",
  "nvidia broadcast",
  "broadcast",
  "iriun",
  "camo",
  "fake",
  "splitcam",
] as const;

export function isSuspiciousCameraLabel(label: string): boolean {
  const lower = label.toLowerCase();
  return SUSPICIOUS_CAMERA_KEYWORDS.some((keyword) => lower.includes(keyword));
}

/**
 * Detects if the active camera stream is a software-based or virtual camera.
 */
export function detectVirtualCamera(stream?: MediaStream | null): VirtualCameraCheck {
  try {
    const track = stream?.getVideoTracks?.()[0];
    const trackLabel = track?.label?.trim() || "";

    if (trackLabel && isSuspiciousCameraLabel(trackLabel)) {
      return {
        isVirtual: true,
        confidence: "high",
        reason: `A virtual or spoofed camera was detected: "${trackLabel}". Please switch to your device's physical hardware camera.`,
        matchedLabel: trackLabel,
        matchedDeviceId: track?.getSettings?.().deviceId,
      };
    }

    return {
      isVirtual: false,
      confidence: "medium",
      reason: "Active camera is valid",
    };
  } catch (error: any) {
    return {
      isVirtual: false,
      confidence: "low",
      reason: error?.message || "Detection failed",
    };
  }
}

/**
 * Validates camera resolution and frame rate to detect anomalies.
 */
export function inspectCameraStreamQuality(stream?: MediaStream | null): StreamQualityCheck {
  const track = stream?.getVideoTracks?.()[0];
  if (!track) {
    return { isSuspicious: false, reason: "No active video track" };
  }

  const { width = 0, height = 0, frameRate = 0 } = track.getSettings?.() ?? {};

  // Unusual streams often generated by virtual driver loops or screen grabs
  if (width > 3840 || height > 2160 || (frameRate && frameRate > 60)) {
    return {
      isSuspicious: true,
      reason: `Unusual camera stream dimensions: ${width}x${height} @ ${frameRate}fps.`,
    };
  }

  return {
    isSuspicious: false,
    reason: "Stream resolution and framerate normal",
  };
}

/**
 * Central proctoring check runner on an active MediaStream.
 */
export async function runProctoringChecks(stream?: MediaStream | null): Promise<ProctoringViolation[]> {
  const violations: ProctoringViolation[] = [];
  if (!stream) return violations;

  const virtualCheck = detectVirtualCamera(stream);
  if (virtualCheck.isVirtual) {
    violations.push({
      type: "VIRTUAL_CAMERA",
      severity: "HIGH",
      ...virtualCheck,
    });
  }

  const qualityCheck = inspectCameraStreamQuality(stream);
  if (qualityCheck.isSuspicious) {
    violations.push({
      type: "CAMERA_QUALITY",
      severity: "MEDIUM",
      ...qualityCheck,
    });
  }

  return violations;
}
